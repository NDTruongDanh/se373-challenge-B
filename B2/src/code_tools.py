"""Internal SDK callable ONLY from inside run_code (Code Mode runtime).

The LLM never sees raw logs: these helpers run inside the sandbox and only
the aggregated `result` leaves the runtime. Every byte scanned here is
counted in RAW_STATS so the demo can prove scanned >> returned.
"""
from __future__ import annotations

from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
LOG_DIR = REPO_ROOT / "logs"  # shared fixture (generated by B1/generate_logs.py)

ALLOWED_LOGS = {"app.log", "test_run.log", "grep_noise.log"}

# Counts everything the sandbox code scanned (never enters LLM context).
RAW_STATS = {"chars": 0, "lines": 0, "calls": 0}


def reset_stats() -> None:
    RAW_STATS["chars"] = 0
    RAW_STATS["lines"] = 0
    RAW_STATS["calls"] = 0


def _bump(text: str, lines: int = 0) -> None:
    RAW_STATS["chars"] += len(text)
    RAW_STATS["lines"] += lines if lines else (text.count("\n") + 1 if text else 0)
    RAW_STATS["calls"] += 1


def _resolve(name: str) -> Path:
    if name not in ALLOWED_LOGS:
        raise ValueError(f"blocked: {name!r} not in {sorted(ALLOWED_LOGS)} (path confinement)")
    path = (LOG_DIR / name).resolve()
    if LOG_DIR.resolve() not in path.parents:
        raise ValueError(f"blocked: path escape {name!r}")
    if not path.exists():
        raise FileNotFoundError(f"{name} not found in logs/. Run: uv run python ../B1/generate_logs.py")
    return path


def list_logs() -> list[str]:
    """List available log files."""
    files = sorted(p.name for p in LOG_DIR.glob("*.log") if p.name in ALLOWED_LOGS)
    _bump("\n".join(files))
    return files


def read_lines(name: str, offset: int = 0, limit: int = 500) -> list[str]:
    """Read up to `limit` lines from `name` starting at `offset` (max 8000)."""
    if limit < 0 or limit > 8000:
        raise ValueError("limit must be 0..8000 (aggregate inside runtime, don't dump)")
    if offset < 0:
        raise ValueError("offset must be >= 0")
    path = _resolve(name)
    with path.open(encoding="utf-8") as f:
        lines = f.read().splitlines()
    chunk = lines[offset : offset + limit]
    _bump("\n".join(chunk), len(chunk))
    return chunk


def grep_count(name: str, pattern: str) -> int:
    """Count lines in `name` containing `pattern` (case-insensitive)."""
    if not pattern:
        raise ValueError("pattern must be non-empty")
    path = _resolve(name)
    n = 0
    total_chars = 0
    total_lines = 0
    with path.open(encoding="utf-8") as f:
        for line in f:
            total_lines += 1
            total_chars += len(line)
            if pattern.lower() in line.lower():
                n += 1
    RAW_STATS["chars"] += total_chars
    RAW_STATS["lines"] += total_lines
    RAW_STATS["calls"] += 1
    return n


def grep_matches(name: str, pattern: str, limit: int = 10) -> list[str]:
    """Return up to `limit` matching lines (max 20 — aggregate, don't dump)."""
    if not pattern:
        raise ValueError("pattern must be non-empty")
    if limit < 0 or limit > 20:
        raise ValueError("limit must be 0..20 (aggregate inside runtime, don't dump)")
    path = _resolve(name)
    out: list[str] = []
    scanned_chars = 0
    scanned_lines = 0
    with path.open(encoding="utf-8") as f:
        for line in f:
            scanned_lines += 1
            scanned_chars += len(line)
            if pattern.lower() in line.lower() and len(out) < limit:
                out.append(line.rstrip("\n"))
    RAW_STATS["chars"] += scanned_chars
    RAW_STATS["lines"] += scanned_lines
    RAW_STATS["calls"] += 1
    return out
